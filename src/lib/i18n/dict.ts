const DICTS: Record<Locale, Dict> = { ko, en };

export function getDict(locale: Locale): Dict {
  return DICTS[locale];
}

/** 차수 표기 — DB의 round_label("1차")은 한국어 전용이므로 영어는 번호로 만든다. */
export function roundLabel(locale: Locale, round: number, koLabel?: string): string {
  return locale === "en" ? `Session ${round}` : koLabel ?? `${round}차`;
}
