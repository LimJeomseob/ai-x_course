-- 대면 세션(1·2·4·5·6·7차) 모집정원 5명 증원: 25 → 30명 (PRD §1.3, §13-A)
-- 온라인 3차(capacity 9999 = 제한 없음)는 변경하지 않는다.
-- 신규 설치는 0002_seed.sql이 이미 30으로 시드하므로 이 UPDATE는 0행 갱신으로 끝난다(멱등).
-- ============================================================================

update public.workshops
   set capacity = 30
 where capacity = 25;
