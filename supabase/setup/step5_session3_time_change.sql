begin;

-- ============================================================================
-- 3차(Day B, 11/11 수, 온라인) 운영시간 변경 (2026-11-09)
--   기존 13:30~15:30 → 변경 15:30~17:30 (강사 일정 조율 결과 반영)
--   신청 마감(11/10 23:59)·정원·장소는 변경 없음
-- ============================================================================

update public.workshops
set start_at = '2026-11-11T15:30:00+09:00'::timestamptz,
    end_at   = '2026-11-11T17:30:00+09:00'::timestamptz
where round = 3;

commit;

-- ── 결과 확인 ──────────────────────────────────────────────────────────────
select round_label,
  to_char(start_at at time zone 'Asia/Seoul', 'MM/DD HH24:MI') as 시작_기대값_11_11_15_30,
  to_char(end_at at time zone 'Asia/Seoul', 'HH24:MI') as 종료_기대값_17_30
from public.workshops where round = 3;
