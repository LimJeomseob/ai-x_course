-- [5/6단계] 대면 세션 모집정원 증원(25 → 30명, 온라인 3차 제외)
-- 원본: supabase/migrations/0005_capacity_30.sql (자동 생성: scripts/build_setup_sql.py — 직접 수정 금지)
-- 실행: Supabase 대시보드 > SQL Editor > New query > 이 파일 전체 붙여넣기 > Run
-- 순서: step1 → step2 → step3 → step4 → step5 → step6 (반드시 번호 순서, 각 파일 1회만) · 실행 전 step4 완료 필요
-- 오류 시 이 단계만 전부 롤백되므로 원인 수정 후 같은 파일을 다시 실행하면 된다.
-- ============================================================================

begin;

-- ============================================================================
-- 대면 세션(1·2·4·5·6·7차) 모집정원 5명 증원: 25 → 30명 (PRD §1.3, §13-A)
-- 온라인 3차(capacity 9999 = 제한 없음)는 변경하지 않는다.
-- 신규 설치는 0002_seed.sql이 이미 30으로 시드하므로 이 UPDATE는 0행 갱신으로 끝난다(멱등).
-- ============================================================================

update public.workshops
   set capacity = 30
 where capacity = 25;

commit;

-- ── 결과 확인 ──────────────────────────────────────────────────────────────
select
  count(*) filter (where capacity = 30) as 대면30명_기대값_6,
  count(*) filter (where capacity >= 9999) as 온라인_기대값_1
from public.workshops;
